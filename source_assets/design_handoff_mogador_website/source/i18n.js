window.MOGADOR_LANGS = ["en", "fr", "ar", "es", "de"];
window.getMogadorLang = function () {
  try {
    var q = new URLSearchParams(location.search).get("lang");
    if (q && window.MOGADOR_I18N[q]) return q;
    var s = localStorage.getItem("mogador_lang");
    if (s && window.MOGADOR_I18N[s]) return s;
  } catch (e) {}
  return "en";
};
window.setMogadorLang = function (lang) {
  try { localStorage.setItem("mogador_lang", lang); } catch (e) {}
  var url = new URL(location.href);
  url.searchParams.set("lang", lang);
  location.href = url.toString();
};
